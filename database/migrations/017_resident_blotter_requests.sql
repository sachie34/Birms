-- Resident-submitted blotter requests from the self-service kiosk.
-- The resident-visible lifecycle uses the five MSIT blotter statuses. Intake review is tracked separately.
CREATE TABLE resident_blotter_requests (
    request_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    reference_no VARCHAR(24) NOT NULL,
    resident_id INT UNSIGNED NOT NULL,
    incident_date DATE NOT NULL,
    incident_time TIME NOT NULL,
    incident_place VARCHAR(150) NOT NULL,
    purok_id INT UNSIGNED NULL,
    incident_type_id INT UNSIGNED NULL,
    narrative TEXT NOT NULL,
    respondent_name VARCHAR(100) NULL,
    respondent_age TINYINT UNSIGNED NULL,
    respondent_address VARCHAR(255) NULL,
    respondent_contact VARCHAR(20) NULL,
    review_status ENUM('Pending','Accepted','Rejected') NOT NULL DEFAULT 'Pending',
    msit_status ENUM('Ongoing','Unresolved','Resolved','Dismissed','Archived') NOT NULL DEFAULT 'Ongoing',
    status_note VARCHAR(500) NULL,
    blotter_id INT UNSIGNED NULL,
    reviewed_by INT UNSIGNED NULL,
    submitted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at DATETIME NULL,
    PRIMARY KEY (request_id),
    UNIQUE KEY uq_resident_blotter_request_ref (reference_no),
    UNIQUE KEY uq_resident_blotter_request_case (blotter_id),
    KEY idx_resident_blotter_review (review_status, submitted_at),
    KEY idx_resident_blotter_status (msit_status, submitted_at),
    KEY idx_resident_blotter_resident (resident_id, submitted_at),
    KEY idx_resident_blotter_purok (purok_id, incident_date),
    CONSTRAINT fk_resident_blotter_resident FOREIGN KEY (resident_id) REFERENCES residents (resident_id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_resident_blotter_purok FOREIGN KEY (purok_id) REFERENCES lookups (lookup_id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_resident_blotter_type FOREIGN KEY (incident_type_id) REFERENCES lookups (lookup_id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_resident_blotter_case FOREIGN KEY (blotter_id) REFERENCES blotters (blotter_id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_resident_blotter_reviewer FOREIGN KEY (reviewed_by) REFERENCES users (user_id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
